  claude: "claude-color",
  codex: "codex-color",
  copilot: "githubcopilot",
  gemini: "geminicli-color",
  cursor: "cursor",
  amp: "amp-color",
  openclaw: "openclaw-color",
  hermes: "hermesagent",
  pi: "pi",
  kimi: "kimi-color",
  qwen: "qwen-color",
  roocode: "roocode",
  kilocode: "kilocode",
  // `kilo` (nicepkg's CLI) is deliberately absent: it is a different project
  // from Kilo-Org's extension above and has no lobehub icon of its own, so it
  // takes the colored-dot fallback rather than wearing someone else's mark.
  kiro: "kiro-color",
  goose: "goose",
  antigravity: "antigravity-color",
  "antigravity-cli": "antigravity-color",
  trae: "trae-color",
  cline: "cline",

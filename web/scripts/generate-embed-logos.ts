/**
 * Generate src/lib/embed/clientLogos.generated.ts from @lobehub/icons-static-svg.
 *
 * Embed cards are standalone SVG responses (CSP `default-src 'none'` and
 * GitHub's camo proxy both block external image fetches), so client logos must
 * be inlined as SVG markup. This script copies the icons the embed templates
 * need out of the icon package at development time so the runtime bundle has
 * no filesystem dependency on node_modules.
 *
 * Run with: bun scripts/generate-embed-logos.ts
 */
import { readFileSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const require = createRequire(import.meta.url);
const iconsDir = join(
  dirname(require.resolve("@lobehub/icons-static-svg/package.json")),
  "icons",
);
const outFile = join(here, "../src/lib/embed/clientLogos.generated.ts");

/**
 * ClientType -> @lobehub/icons-static-svg icon slug. Clients without a
 * matching lobehub icon are omitted and keep the colored-dot fallback.
 */
